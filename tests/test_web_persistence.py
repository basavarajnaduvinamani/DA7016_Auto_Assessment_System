def test_translate_sqlite_spellings_for_postgres():
    assert translate("SELECT * FROM t WHERE a=? AND b=?") == ("SELECT * FROM t WHERE a=%s AND b=%s", None)
    sql, table = translate("INSERT OR IGNORE INTO jobs(submission_id,status) SELECT id,'queued' FROM submissions")
    assert table == "jobs" and sql.startswith("INSERT INTO jobs") and sql.endswith("ON CONFLICT DO NOTHING")
    sql, _ = translate("INSERT OR REPLACE INTO accepted VALUES(?,?,?)")
    assert sql.endswith("ON CONFLICT (submission_id, question_id) DO UPDATE SET teacher_id=EXCLUDED.teacher_id")
    sql, _ = translate("INSERT OR REPLACE INTO blobs(path,data,size,updated_at) VALUES(?,?,?,?)")
    assert "ON CONFLICT (path) DO UPDATE SET data=EXCLUDED.data, size=EXCLUDED.size" in sql
    assert translate("SELECT '5%' FROM t")[0] == "SELECT '5%%' FROM t"
    ddl = translate_ddl("CREATE TABLE x (id INTEGER PRIMARY KEY, n INTEGER, at REAL, d BLOB, e TEXT COLLATE NOCASE)")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in ddl and "DOUBLE PRECISION" in ddl
    assert "BYTEA" in ddl and "NOCASE" not in ddl and "n BIGINT" in ddl


def test_old_sqlite_files_upgrade_in_place(tmp_path):
    import sqlite3

    folder = tmp_path / "old"
    folder.mkdir()
    with sqlite3.connect(folder / "redink.db") as db:
        db.executescript("""
            CREATE TABLE schema_version (version INTEGER NOT NULL); INSERT INTO schema_version VALUES (3);
            CREATE TABLE teachers (id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE COLLATE NOCASE);
            INSERT INTO teachers(name,email) VALUES('Kept','Kept@Example.org');
            CREATE TABLE classes (id INTEGER PRIMARY KEY, teacher_id INTEGER NOT NULL, name TEXT NOT NULL,
                subject TEXT NOT NULL, section TEXT NOT NULL DEFAULT '');
            CREATE TABLE assignments (id INTEGER PRIMARY KEY, class_id INTEGER NOT NULL, title TEXT NOT NULL,
                spec_json TEXT NOT NULL, released INTEGER NOT NULL DEFAULT 0, is_demo INTEGER NOT NULL DEFAULT 0);
        """)
    store = Store(folder, database_url="")
    assert store.teacher_by_email("kept@example.org")["name"] == "Kept"
    with store.connect() as db:
        assert db.execute("SELECT version FROM schema_version").fetchone()[0] == SCHEMA_VERSION
        columns = {r[1] for r in db.execute("PRAGMA table_info(assignments)")}
    assert "feedback_language" in columns


