def test_marked_files_survive_a_wiped_disk(tmp_path, durable_sqlite):
    """A restart on a fresh disk (Render) restores uploads and marked pages from the database."""
    app = create_app(tmp_path / "app")
    store = app.state.store
    assert store.files.durable
    assignment_id, folder = demo_marked_files(store)
    before = sorted(p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file())
    assert any(name.endswith("_marked.pdf") for name in before) and any(name.endswith(".png") for name in before)
    shutil.rmtree(store.root / "files")
    (store.root / "files").mkdir()

    restarted = create_app(tmp_path / "app")
    with TestClient(restarted) as client:
        client.post("/sign-in", data={"email": "demo@redink.local"})
        sheet = restarted.state.store.submissions(assignment_id)[0]
        after = sorted(p.relative_to(folder).as_posix() for p in folder.rglob("*") if p.is_file())
        assert after == before
        marked = client.get(f"/assignments/{assignment_id}/submissions/{sheet['id']}/artifact/marked?index=0")
        assert marked.status_code == 200 and marked.headers["content-type"] == "image/png"
        assert client.get(f"/assignments/{assignment_id}/export/zip").status_code == 200
    count, size = restarted.state.store.files.blobs.usage()
    assert count >= len(before) and size > 0


class FakeS3:
    """Just enough of boto3's S3 client for S3Blobs."""

    def __init__(self):
        self.objects = {}

    def put_object(self, Bucket, Key, Body):
        self.objects[Key] = Body

    def get_object(self, Bucket, Key):
        if Key not in self.objects:
            raise type("NoSuchKey", (Exception,), {})()
        import io

        return {"Body": io.BytesIO(self.objects[Key])}

    def list_objects_v2(self, Bucket, Prefix, **kw):
        keys = sorted(k for k in self.objects if k.startswith(Prefix))
        return {"Contents": [{"Key": k, "Size": len(self.objects[k])} for k in keys], "IsTruncated": False}

    def delete_objects(self, Bucket, Delete):
        for item in Delete["Objects"]:
            self.objects.pop(item["Key"], None)


def test_s3_blob_store_round_trip(tmp_path):
    fake = FakeS3()
    mirror = FileMirror(tmp_path / "files", S3Blobs("bucket", prefix="secondread", client=fake))
    (tmp_path / "files" / "7" / "marked").mkdir(parents=True)
    (tmp_path / "files" / "7" / "marked" / "a.png").write_bytes(b"png")
    mirror.save_tree(tmp_path / "files" / "7")
    assert list(fake.objects) == ["secondread/7/marked/a.png"]
    shutil.rmtree(tmp_path / "files" / "7")
    FileMirror(tmp_path / "files", S3Blobs("bucket", prefix="secondread", client=fake)).restore(7)
    assert (tmp_path / "files" / "7" / "marked" / "a.png").read_bytes() == b"png"
    assert S3Blobs("bucket", prefix="secondread", client=fake).get("missing") is None
    mirror.forget(7)
    assert fake.objects == {} and not (tmp_path / "files" / "7").exists()


def test_mirror_ignores_paths_outside_the_files_folder(tmp_path):
    blobs = DatabaseBlobs(Store(tmp_path / "s", database_url="").connect)
    mirror = FileMirror(tmp_path / "s" / "files", blobs)
    outside = tmp_path / "elsewhere.txt"
    outside.write_text("x")
    mirror.save(outside)
    assert blobs.usage() == (0, 0)
    with pytest.raises(ValueError):
        blobs.keys("1_%/")


def test_migrate_copies_a_sqlite_workspace(tmp_path, capsys):
    """Copy the seeded demo workspace into a new database (Postgres when the suite runs on it)."""
    source_app = create_app(tmp_path / "source", seed_samples=True) if not os.getenv("DATABASE_URL") else None
    if source_app is None:
        # Build the SQLite source explicitly while DATABASE_URL points at the test Postgres.
        url = os.environ.pop("DATABASE_URL")
        try:
            create_app(tmp_path / "source")
        finally:
            os.environ["DATABASE_URL"] = url
    target_url = os.getenv("DATABASE_URL")
    summary = migrate(target_url, tmp_path / "target", tmp_path / "source")
    assert summary["copied"]["teachers"] == 1 and summary["copied"]["submissions"] >= 3 and summary["files"] > 0
    target = Store(tmp_path / "target", database_url=target_url)
    demo = target.teacher_by_email("demo@redink.local")
    assignment = target.assignments(target.classes(demo["id"])[0]["id"])[0]
    sheet = target.submissions(assignment["id"])[0]
    assert str(tmp_path / "target") in sheet["path"] and str(tmp_path / "source") not in sheet["artifacts_json"]
    assert target.effective_grade(sheet) is not None
    # New rows get fresh ids after the copy (sequences moved past the copied ids).
    new_class = target.create_class(demo["id"], "New", "Subject")
    assert new_class > max(c["id"] for c in target.classes(demo["id"]) if c["id"] != new_class)
    with pytest.raises(SystemExit):
        migrate(target_url, tmp_path / "target", tmp_path / "source")
    assert main(["migrate", "--data-dir", str(tmp_path / "fresh")]) == 0
    assert "Schema is current" in capsys.readouterr().out
